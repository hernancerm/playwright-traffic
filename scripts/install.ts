/**
 * Puts `curler` and `curlr` on PATH as shims into this repo.
 *
 * Not `deno install`: that shim runs with `--no-config`, and passing --config
 * makes it copy the file next to the shim, where the workspace's `./curler`,
 * `./collection` and `./reporter` no longer resolve. These shims name the real
 * config instead, so the workspace stays intact.
 */

import { dirname, fromFileUrl, join } from '@std/path';

const root = dirname(dirname(fromFileUrl(import.meta.url)));
const binDir = join(Deno.env.get('HOME')!, '.local', 'bin');

// `curler` loads your collection file, which runs it, so it gets everything.
// `curlr` only shells out to curl and juggles the header temp file.
const shims = [
  { name: 'curler', entry: 'collection/cli.ts', perms: ['-A'] },
  {
    name: 'curlr',
    entry: 'reporter/main.ts',
    perms: ['--allow-run=curl', '--allow-read', '--allow-write'],
  },
];

await Deno.mkdir(binDir, { recursive: true });

for (const { name, entry, perms } of shims) {
  const path = join(binDir, name);
  await Deno.writeTextFile(
    path,
    `#!/bin/sh\n# generated by \`deno task install\`\nexec deno run --quiet ` +
      `--config '${join(root, 'deno.json')}' ${perms.join(' ')} ` +
      `'${join(root, entry)}' "$@"\n`,
  );
  await Deno.chmod(path, 0o755);
  console.log(`installed ${path}`);
}
