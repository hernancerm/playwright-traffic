/**
 * Puts `curler` on PATH as a shim into this repo.
 *
 * The shim picks a permission set from the subcommand. `run-curl` only shells
 * out to curl and writes a temp file for the headers; everything else imports
 * your collection file, which runs it, so it gets `-A`. One binary keeps that
 * split without a second name to remember.
 *
 * Not `deno install`: its shim runs with `--no-config`, and passing --config
 * makes it copy the file next to the shim, where the workspace's `./builder`,
 * `./collection` and `./reporter` no longer resolve. This names the real
 * config instead.
 */

import { dirname, fromFileUrl, join } from '@std/path';

const root = dirname(dirname(fromFileUrl(import.meta.url)));
const binDir = join(Deno.env.get('HOME')!, '.local', 'bin');
const config = join(root, 'deno.json');

const REPORTER_PERMS = '--allow-run=curl --allow-read --allow-write';

const shim = `#!/bin/sh
# generated by \`deno task install\`
case "$1" in
  run-curl|run)
    shift
    exec deno run --quiet --config '${config}' ${REPORTER_PERMS} \\
      '${join(root, 'reporter/main.ts')}' "$@" ;;
  *)
    exec deno run --quiet --config '${config}' -A \\
      '${join(root, 'collection/cli.ts')}' "$@" ;;
esac
`;

await Deno.mkdir(binDir, { recursive: true });

const path = join(binDir, 'curler');
await Deno.writeTextFile(path, shim);
await Deno.chmod(path, 0o755);
console.log(`installed ${path}`);

// `curlr` was the reporter's own binary before the subcommand took over.
const stale = join(binDir, 'curlr');
try {
  await Deno.remove(stale);
  console.log(`removed ${stale}`);
} catch {
  // Never installed, or already gone.
}
